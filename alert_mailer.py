import smtplib
from email.mime.multipart import MIMEMultipart
from email.mime.text import MIMEText

import os
from dotenv import load_dotenv

load_dotenv()
EMAIL_SENDER = os.getenv("EMAIL_SENDER")
EMAIL_PASSWORD = os.getenv("EMAIL_PASSWORD")
# ----------------------------------

def send_alert_confirmation(user_email, ticker, target_price):
    print(f"Enviando correo de confirmación a {user_email}...")
    
    # Configurar el mensaje
    msg = MIMEMultipart()
    msg['From'] = f"Market Intelligence <{EMAIL_SENDER}>"
    msg['To'] = user_email
    msg['Subject'] = f"Alert Confirmed: {ticker} Target Price Set"

    # Diseño HTML corporativo (Modo Oscuro)
    html_body = f"""
    <html>
    <body style="font-family: Arial, sans-serif; background-color: #0B0F19; color: #e2e8f0; margin: 0; padding: 40px 20px;">
        <div style="max-width: 600px; margin: 0 auto; background-color: #0F172A; border: 1px solid #1e293b; border-radius: 12px; overflow: hidden;">
            
            <!-- Header -->
            <div style="background-color: #1e40af; padding: 24px; text-align: center;">
                <h2 style="color: #ffffff; margin: 0; font-size: 20px; letter-spacing: 1px;">QUANTITATIVE MARKET PIPELINE</h2>
            </div>
            
            <!-- Body -->
            <div style="padding: 32px;">
                <h3 style="color: #ffffff; font-size: 22px; margin-top: 0;">Alert Successfully Registered</h3>
                <p style="color: #94a3b8; font-size: 16px; line-height: 1.6;">
                    Hello,<br><br>
                    Your automated price alert has been successfully registered in our database. Our systems are now monitoring the asset.
                </p>
                
                <!-- Target Box -->
                <div style="background-color: #151E32; border-left: 4px solid #3b82f6; padding: 16px; margin: 24px 0; border-radius: 4px;">
                    <p style="margin: 0; color: #cbd5e1; font-size: 14px;"><strong>ASSET:</strong> {ticker}</p>
                    <p style="margin: 8px 0 0 0; color: #cbd5e1; font-size: 14px;"><strong>TARGET PRICE:</strong> ${target_price:.2f}</p>
                </div>
                
                <!-- The Disclaimer you asked for -->
                <div style="background-color: rgba(245, 158, 11, 0.1); border: 1px solid rgba(245, 158, 11, 0.2); padding: 16px; border-radius: 8px;">
                    <p style="margin: 0; color: #fbbf24; font-size: 13px; line-height: 1.5;">
                        <strong>⚠️ IMPORTANT SYSTEM NOTICE:</strong><br>
                        Please note that this is an End-of-Day (EOD) reporting system. Price checks are executed dynamically via our BigQuery pipeline <strong>once daily at market close</strong>. You will be notified if the target price is met at the end of the trading session, not in real-time.
                    </p>
                </div>
            </div>
            
            <!-- Footer -->
            <div style="background-color: #0B0F19; padding: 20px; text-align: center; border-top: 1px solid #1e293b;">
                <p style="color: #64748b; font-size: 12px; margin: 0;">Automated message generated by Python & Google Cloud Platform.</p>
            </div>
        </div>
    </body>
    </html>
    """
    
    msg.attach(MIMEText(html_body, 'html'))

    try:
        # Conectar al servidor de Gmail y enviar
        server = smtplib.SMTP('smtp.gmail.com', 587)
        server.starttls()
        server.login(EMAIL_SENDER, EMAIL_PASSWORD)
        server.send_message(msg)
        server.quit()
        print("✅ ¡Correo enviado exitosamente!")
    except Exception as e:
        print(f"❌ Error enviando el correo: {e}")

